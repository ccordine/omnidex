// The child is an actual stdio process, not a mocked connection. It records only
// fixture protocol, checks the private mount, and never contacts a model.
func TestParserProcessHelper(t *testing.T) {
	index := -1
	for i, arg := range os.Args {
		if arg == "--parser-fixture" {
			index = i + 1
			break
		}
	}
	if index < 0 {
		return
	}
	root := os.Args[index]
	arguments := strings.Join(os.Args[index+1:], " ")
	for _, required := range []string{"features.skip_host_skill_discovery=true", `developer_instructions=""`, "features.shell_tool=false", "features.plugins=false", "features.browser_use=false", "features.computer_use=false", "features.image_generation=false", "features.code_mode_host=false", "features.skill_search=false", "features.code_mode=false", "include_permissions_instructions=false", "include_collaboration_mode_instructions=false", "include_environment_context=false", "skills.include_instructions=false", "skills.bundled.enabled=false"} {
		if !strings.Contains(arguments, required) {
			os.Exit(17)
		}
	}
	log, err := os.OpenFile(filepath.Join(root, "protocol"), os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0600)
	if err != nil {
		os.Exit(10)
	}
	defer log.Close()
	if data, err := os.ReadFile(filepath.Join(os.Getenv("CODEX_HOME"), "AGENTS.md")); err == nil && len(data) != 0 {
		os.Exit(11)
	}
	if data, err := os.ReadFile(filepath.Join(os.Getenv("CODEX_HOME"), "auth.json")); err != nil || string(data) != "fixture-identity" {
		os.Exit(12)
	}
	fmt.Fprintf(log, "process %d\n", os.Getpid())
	scan := bufio.NewScanner(os.Stdin)
	scan.Buffer(make([]byte, 4096), 1<<20)
	thread := 0
	for scan.Scan() {
		var request struct {
			ID     *int           `json:"id"`
			Method string         `json:"method"`
			Params map[string]any `json:"params"`
		}
		if json.Unmarshal(scan.Bytes(), &request) != nil {
			os.Exit(13)
		}
		fmt.Fprintln(log, string(scan.Bytes()))
		result := any(map[string]any{})
		switch request.Method {
		case "initialize":
		case "initialized":
			continue
		case "config/read":
			result = map[string]any{"config": map[string]any{"mcp_servers": map[string]any{"fixture": map[string]any{}}}}
		case "thread/start":
			thread++
			if request.Params["ephemeral"] != true || request.Params["developerInstructions"] != "" || request.Params["model"] != "gpt-6.1-sol" {
				os.Exit(14)
			}
			result = map[string]any{"model": "gpt-6.1-sol", "thread": map[string]any{"id": fmt.Sprint(thread)}}
		case "turn/start":
			if request.Params["effort"] != "low" {
				os.Exit(15)
			}
			if strings.Contains(string(scan.Bytes()), "block-fixture") {
				time.Sleep(time.Hour)
			}
			result = map[string]any{"turn": map[string]any{"id": "turn"}}
		default:
			os.Exit(16)
		}
		json.NewEncoder(os.Stdout).Encode(map[string]any{"id": request.ID, "result": result})
		if request.Method == "turn/start" {
			json.NewEncoder(os.Stdout).Encode(map[string]any{"method": "thread/tokenUsage/updated", "params": map[string]any{"threadId": fmt.Sprint(thread), "turnId": "turn", "tokenUsage": map[string]any{"last": map[string]int{"inputTokens": 40, "outputTokens": 12, "reasoningOutputTokens": 5, "totalTokens": 52}}}})
			json.NewEncoder(os.Stdout).Encode(map[string]any{"method": "item/completed", "params": map[string]any{"threadId": fmt.Sprint(thread), "turnId": "turn", "item": map[string]any{"type": "agentMessage", "phase": "final_answer", "text": "{}"}}})
			json.NewEncoder(os.Stdout).Encode(map[string]any{"method": "turn/completed", "params": map[string]any{"threadId": fmt.Sprint(thread), "turn": map[string]any{"id": "turn", "status": "completed"}}})
		}
	}
	os.Exit(0)
}

func parserFixture(t *testing.T, instructions bool) (*Client, string, context.CancelFunc) {
	t.Helper()
	root := t.TempDir()
	profile := filepath.Join(root, "profile")
	if err := os.Mkdir(profile, 0700); err != nil {
		t.Fatal(err)
	}
	for name, data := range map[string]string{"models_cache.json": `{"models":[{"slug":"gpt-6.1-sol","tool_mode":"code_mode_only"}]}`, "auth.json": "fixture-identity", "config.toml": "developer_instructions = 'unrelated fixture instruction'"} {
		if err := os.WriteFile(filepath.Join(profile, name), []byte(data), 0600); err != nil {
			t.Fatal(err)
		}
	}
	if instructions {
		if err := os.WriteFile(filepath.Join(profile, "AGENTS.md"), []byte("unrelated global instruction"), 0600); err != nil {
			t.Fatal(err)
		}
	}
	t.Setenv("CODEX_HOME", profile)
	executable, err := os.Executable()
	if err != nil {
		t.Fatal(err)
	}
	command := filepath.Join(root, "provider")
	// Paths are generated by testing.TempDir, but quote them as shell data.
	quote := func(s string) string { return "'" + strings.ReplaceAll(s, "'", "'\\''") + "'" }
	if err := os.WriteFile(command, []byte("#!/bin/sh\nexec "+quote(executable)+" -test.run=^TestParserProcessHelper$ -- --parser-fixture "+quote(root)+" \"$@\"\n"), 0700); err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	client, err := NewParser(ctx, command, root, 3*time.Second)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { cancel(); client.Close() })
	return client, root, cancel
}

func parserRequest(t *testing.T, client *Client, prompt string) llm.PreparedModel {
	t.Helper()
	prepared, err := llm.PrepareNativeRequest(client, llm.PreparedModel{Protocol: llm.ExactPreparedProtocolPlainCompletionV4, BaseModel: "gpt-6.1-sol", ContextModel: "gpt-6.1-sol", Prompt: prompt, MaxOutputTokens: 2048, OutputLimitMode: llm.ExactPreparedOutputLimitExplicit, ContextTokens: 32768})
	if err != nil {
		t.Fatal(err)
	}
	return prepared
}

func TestParserProcessReuseAndThreadIsolation(t *testing.T) {
	for _, instructions := range []bool{false, true} {
		t.Run(fmt.Sprint(instructions), func(t *testing.T) {
			client, root, cancel := parserFixture(t, instructions)
			for i := 0; i < 2; i++ {
				if _, err := client.GeneratePreparedExact(context.Background(), parserRequest(t, client, "fixture question")); err != nil {
					t.Fatal(err)
				}
			}
			data, err := os.ReadFile(filepath.Join(root, "protocol"))
			if err != nil {
				t.Fatal(err)
			}
			text := string(data)
			for token, want := range map[string]int{"process ": 1, `"method":"initialize"`: 1, `"method":"thread/start"`: 2, `"method":"turn/start"`: 2} {
				if strings.Count(text, token) != want {
					t.Fatalf("%s count: %s", token, text)
				}
			}
			if !strings.Contains(text, `"threadId":"1"`) || !strings.Contains(text, `"threadId":"2"`) || strings.Contains(text, `"thread/resume"`) {
				t.Fatal("questions shared a native thread")
			}
			if !strings.Contains(text, `"fixture":{"enabled":false}`) || !strings.Contains(text, `"shell_tool":false`) || !strings.Contains(text, `"project_doc_max_bytes":0`) {
				t.Fatalf("tools/instructions not disabled: %s", text)
			}
			if instructions {
				data, _ := os.ReadFile(filepath.Join(root, "profile", "AGENTS.md"))
				if string(data) != "unrelated global instruction" {
					t.Fatal("host policy edited")
				}
			}
			data, _ = os.ReadFile(filepath.Join(root, "profile", "config.toml"))
			if string(data) != "developer_instructions = 'unrelated fixture instruction'" {
				t.Fatal("configuration edited")
			}
			connection := client.parser.connection
			cancel()
			if err := client.Close(); err != nil {
				t.Fatal(err)
			}
			if connection.process.ProcessState == nil {
				t.Fatal("child not reaped")
			}
			entries, err := os.ReadDir(filepath.Join(root, "bin", "agent-runtime"))
			if err != nil || len(entries) != 0 {
				t.Fatalf("scratch not cleaned: %v %v", entries, err)
			}
			if _, err := client.GeneratePreparedExact(context.Background(), parserRequest(t, client, "closed")); err == nil {
				t.Fatal("closed parser accepted request")
			}
		})
	}
}

func TestParserProcessCancellationAndRecovery(t *testing.T) {
	client, root, _ := parserFixture(t, false)
	ctx, cancel := context.WithTimeout(context.Background(), 200*time.Millisecond)
	defer cancel()
	start := time.Now()
	if _, err := client.GeneratePreparedExact(ctx, parserRequest(t, client, "block-fixture")); err == nil {
		t.Fatal("canceled generation succeeded")
	}
	if time.Since(start) > 2*time.Second {
		t.Fatal("cancellation did not interrupt read")
	}
	if _, err := client.GeneratePreparedExact(context.Background(), parserRequest(t, client, "fresh question")); err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(filepath.Join(root, "protocol"))
	if strings.Count(string(data), "process ") != 2 {
		t.Fatalf("canceled transport was reused: %s", data)
	}
}

func TestParserProcessBoundAndWaitingCancellation(t *testing.T) {
	client, root, _ := parserFixture(t, false)
	prepared := parserRequest(t, client, "bounded fixture")
	for i := 0; i < 65; i++ {
		if _, err := client.GeneratePreparedExact(context.Background(), prepared); err != nil {
			t.Fatal(err)
		}
	}
	data, _ := os.ReadFile(filepath.Join(root, "protocol"))
	if strings.Count(string(data), "process ") != 2 {
		t.Fatal("process lifetime did not bound native thread retention")
	}
	client.parser.gate <- struct{}{}
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Millisecond)
	defer cancel()
	if _, err := client.GeneratePreparedExact(ctx, prepared); err == nil {
		t.Fatal("waiting cancellation succeeded")
	}
	<-client.parser.gate
	if _, err := client.GeneratePreparedExact(context.Background(), prepared); err != nil {
		t.Fatal(err)
	}
}

func TestParserProcessCloseCancelsActiveGeneration(t *testing.T) {
	client, root, _ := parserFixture(t, false)
	prepared := parserRequest(t, client, "block-fixture")
	finished := make(chan error, 1)
	go func() { _, err := client.GeneratePreparedExact(context.Background(), prepared); finished <- err }()
	deadline := time.Now().Add(time.Second)
	for {
		data, _ := os.ReadFile(filepath.Join(root, "protocol"))
		if strings.Contains(string(data), `"method":"turn/start"`) {
			break
		}
		if time.Now().After(deadline) {
			t.Fatal("fixture did not start")
		}
		time.Sleep(time.Millisecond)
	}
	start := time.Now()
	if err := client.Close(); err != nil {
		t.Fatal(err)
	}
	if time.Since(start) > 2*time.Second {
		t.Fatal("close did not interrupt active generation")
	}
	if err := <-finished; err == nil {
		t.Fatal("shutdown generation succeeded")
	}
	entries, err := os.ReadDir(filepath.Join(root, "bin", "agent-runtime"))
	if err != nil || len(entries) != 0 {
		t.Fatal("active shutdown left scratch")
	}
}
