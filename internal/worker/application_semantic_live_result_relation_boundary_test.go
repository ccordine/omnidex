package worker

import (
	"testing"

	"github.com/gryph/omnidex/internal/assemblyline"
)

const liveApplicationResultRelationBoundaryScope = "live-application-result-relation-boundary-v7"

func TestLiveApplicationResultRelationBoundaryQualification(t *testing.T) {
	ctx, modelName, transport := newLiveApplicationSemanticBoundaryTransport(
		t,
		liveApplicationResultRelationBoundaryScope,
	)
	fixtures := []struct {
		name, candidate, relation string
	}{
		{
			name:      "text-transformation",
			candidate: "Display submitted text converted to Unicode lowercase.",
			relation:  assemblyline.ApplicationRequirementExplicitResultRelation,
		},
		{
			name:      "numeric-ordering",
			candidate: "Display submitted numbers ordered in ascending numeric order.",
			relation:  assemblyline.ApplicationRequirementExplicitResultRelation,
		},
		{
			name:      "document-recorded-key",
			candidate: "Display uploaded documents grouped by their recorded owner identifier.",
			relation:  assemblyline.ApplicationRequirementExplicitResultRelation,
		},
		{
			name:      "runtime-filter-expression",
			candidate: "Display the records selected by evaluating the filter expression entered by the user.",
			relation:  assemblyline.ApplicationRequirementExplicitResultRelation,
		},
		{
			name:      "runtime-recurrence-rule",
			candidate: "Display occurrence dates generated by evaluating the recurrence rule entered by the user.",
			relation:  assemblyline.ApplicationRequirementExplicitResultRelation,
		},
		{
			name:      "runtime-performed-calculation",
			candidate: "Display a numeric result for the calculation performed by the user.",
			relation:  assemblyline.ApplicationRequirementExplicitResultRelation,
		},
		{
			name:      "runtime-performed-calculation-declarative",
			candidate: "The application displays a numeric result for the calculation performed by the user.",
			relation:  assemblyline.ApplicationRequirementExplicitResultRelation,
		},
		{
			name:      "runtime-selected-operation-declarative",
			candidate: "The display reports the result of the operation selected and performed by the operator.",
			relation:  assemblyline.ApplicationRequirementExplicitResultRelation,
		},
		{
			name:      "runtime-supplied-formula-declarative",
			candidate: "The interface displays the value obtained from the formula supplied by its operator.",
			relation:  assemblyline.ApplicationRequirementExplicitResultRelation,
		},
		{
			name:      "action-form-named-transformation",
			candidate: "The finished software resizes supplied images.",
			relation:  assemblyline.ApplicationRequirementExplicitResultRelation,
		},
		{
			name:      "governed-value-decoding-without-presentation",
			candidate: "The finished software decodes the value encoded in each supplied symbol.",
			relation:  assemblyline.ApplicationRequirementExplicitResultRelation,
		},
		{
			name:      "runtime-calculated-without-rule",
			candidate: "Display a result calculated at runtime.",
			relation:  assemblyline.ApplicationRequirementMissingResultRelation,
		},
		{
			name:      "runtime-computed-output-declarative",
			candidate: "The display reports an output computed during execution.",
			relation:  assemblyline.ApplicationRequirementMissingResultRelation,
		},
		{
			name:      "document-unstated-key",
			candidate: "Display uploaded documents in the most useful groups.",
			relation:  assemblyline.ApplicationRequirementMissingResultRelation,
		},
		{
			name:      "filter-without-expression",
			candidate: "Display the correctly selected records.",
			relation:  assemblyline.ApplicationRequirementMissingResultRelation,
		},
		{
			name:      "dates-without-recurrence-rule",
			candidate: "Display the appropriate future occurrence dates.",
			relation:  assemblyline.ApplicationRequirementMissingResultRelation,
		},
		{
			name:      "telemetry-warning",
			candidate: "Show a prominent warning when a telemetry packet is invalid.",
			relation:  assemblyline.ApplicationRequirementNoDerivedResult,
		},
		{
			name:      "action-without-governed-value",
			candidate: "The finished software archives each received message.",
			relation:  assemblyline.ApplicationRequirementNoDerivedResult,
		},
		{
			name:      "telemetry-selection",
			candidate: "Show the best recovery route when a telemetry packet is invalid.",
			relation:  assemblyline.ApplicationRequirementMissingResultRelation,
		},
	}
	for _, fixture := range fixtures {
		t.Run(fixture.name, func(t *testing.T) {
			finalInput := liveApplicationResultRelationInput(t, fixture.candidate)
			derivedInput := assemblyline.ApplicationRequirementCandidateResultPresenceInput{
				Candidate: fixture.candidate, Kind: finalInput.Kind,
				Cardinality: finalInput.Cardinality,
				Dimension:   assemblyline.ApplicationRequirementDerivedValueDimension,
			}
			job, err := assemblyline.NewApplicationRequirementCandidateResultPresenceJob(derivedInput)
			if err != nil {
				t.Fatal(err)
			}
			start := transport.callCount()
			raw, err := transport.execute(ctx, job, modelName)
			if err != nil {
				t.Fatal(err)
			}
			derived, err := assemblyline.DecodeApplicationRequirementCandidateResultPresenceResult(
				derivedInput,
				raw.Candidate,
			)
			if err != nil {
				t.Fatal(err)
			}
			var determining *assemblyline.ApplicationRequirementCandidateResultPresenceResult
			if derived.Presence == assemblyline.ApplicationRequirementCandidateResultPresent {
				determiningInput := assemblyline.ApplicationRequirementCandidateResultPresenceInput{
					Candidate: fixture.candidate, Kind: finalInput.Kind,
					Cardinality:          finalInput.Cardinality,
					Dimension:            assemblyline.ApplicationRequirementDeterminingRelationDimension,
					DerivedValuePresence: &derived,
				}
				determiningJob, err := assemblyline.NewApplicationRequirementCandidateResultPresenceJob(
					determiningInput,
				)
				if err != nil {
					t.Fatal(err)
				}
				determiningRaw, err := transport.execute(ctx, determiningJob, modelName)
				if err != nil {
					t.Fatal(err)
				}
				decoded, err := assemblyline.DecodeApplicationRequirementCandidateResultPresenceResult(
					determiningInput,
					determiningRaw.Candidate,
				)
				if err != nil {
					t.Fatal(err)
				}
				determining = &decoded
			}
			result, err := assemblyline.ResolveApplicationRequirementCandidateResultRelation(
				finalInput,
				derived,
				determining,
			)
			if err != nil {
				t.Fatal(err)
			}
			if result.Relation != fixture.relation {
				t.Fatalf("relation=%q, want %q", result.Relation, fixture.relation)
			}
			calls := transport.callsFrom(start)
			wantCalls := 2
			if fixture.relation == assemblyline.ApplicationRequirementNoDerivedResult {
				wantCalls = 1
			}
			if len(calls) != wantCalls {
				t.Fatalf("unexpected exact station calls: %+v", calls)
			}
			for _, call := range calls {
				if call.kind != assemblyline.WorkApplicationRequirementCandidateResultRelation {
					t.Fatalf("unexpected exact station call: %+v", call)
				}
			}
			logLiveCodingQualification(t, fixture.name, modelName, "not-applicable", calls)
		})
	}
}

func liveApplicationResultRelationInput(
	t *testing.T,
	candidate string,
) assemblyline.ApplicationRequirementCandidateResultRelationInput {
	t.Helper()
	kind := applicationRequirementCandidateKindReceiptForTest(
		t,
		candidate,
		assemblyline.ApplicationRequirementCandidateTaskLocal,
	)
	cardinalityInput := assemblyline.ApplicationRequirementCandidateCardinalityInput{
		Candidate: candidate,
	}
	cardinality, err := assemblyline.DecodeApplicationRequirementCandidateCardinalityResult(
		cardinalityInput,
		assemblyline.ApplicationRequirementOneRuntimeOutcome,
	)
	if err != nil {
		t.Fatal(err)
	}
	return assemblyline.ApplicationRequirementCandidateResultRelationInput{
		Candidate:   candidate,
		Kind:        kind,
		Cardinality: cardinality,
	}
}
